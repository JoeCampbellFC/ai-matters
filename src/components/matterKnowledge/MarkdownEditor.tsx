import { useState } from 'react'
import ReactMarkdown from 'react-markdown'
import remarkGfm from 'remark-gfm'
import { AlertCircle } from 'lucide-react'
import { Alert, AlertDescription } from '@/components/ui/alert'
import { Button } from '@/components/ui/button'
import { Input } from '@/components/ui/input'
import { Label } from '@/components/ui/label'
import { ScrollArea } from '@/components/ui/scroll-area'
import { Textarea } from '@/components/ui/textarea'

/**
 * Split-pane Markdown editor: a plain Textarea (not a rich WYSIWYG editor --
 * this app's Matter Knowledge content is authored/regenerated by the
 * research agent and only occasionally hand-edited, so a heavier editor
 * dependency isn't justified) with a live react-markdown preview reusing
 * MarkdownViewer's same AST-to-React rendering (no raw HTML, same
 * sanitization guarantee).
 */
export function MarkdownEditor({
  initialContent,
  saving,
  error,
  onSave,
  onCancel,
  showChangeSummary = true,
  saveLabel = 'Save New Version',
}: {
  initialContent: string
  saving: boolean
  error?: string
  onSave: (content: string, changeSummary?: string) => void
  onCancel: () => void
  /** Hide the "change summary" field for callers with no version-history concept (e.g. editing a research playbook). */
  showChangeSummary?: boolean
  saveLabel?: string
}) {
  const [content, setContent] = useState(initialContent)
  const [changeSummary, setChangeSummary] = useState('')
  const dirty = content !== initialContent

  return (
    <div className="flex flex-col gap-3">
      <div className="grid grid-cols-1 gap-3 lg:grid-cols-2">
        <div className="flex flex-col gap-1.5">
          <Label htmlFor="markdown-editor">Markdown</Label>
          <Textarea
            id="markdown-editor"
            value={content}
            onChange={(e) => setContent(e.target.value)}
            className="h-[70vh] min-h-[28rem] font-mono text-xs"
          />
        </div>
        <div className="flex flex-col gap-1.5">
          <Label>Live Preview</Label>
          <ScrollArea className="h-[70vh] min-h-[28rem] rounded-md border border-border p-4">
            <article className="prose prose-sm dark:prose-invert max-w-none">
              <ReactMarkdown remarkPlugins={[remarkGfm]}>{content}</ReactMarkdown>
            </article>
          </ScrollArea>
        </div>
      </div>

      {showChangeSummary && (
        <div className="flex flex-col gap-1.5">
          <Label htmlFor="change-summary">Change summary (optional)</Label>
          <Input
            id="change-summary"
            value={changeSummary}
            onChange={(e) => setChangeSummary(e.target.value)}
            placeholder="What did you change, and why?"
          />
        </div>
      )}

      {error && (
        <Alert variant="destructive">
          <AlertCircle className="size-4" />
          <AlertDescription>{error}</AlertDescription>
        </Alert>
      )}

      <div className="flex items-center gap-2">
        <Button disabled={!dirty || saving} onClick={() => onSave(content, changeSummary.trim() || undefined)}>
          {saveLabel}
        </Button>
        <Button variant="outline" disabled={saving} onClick={onCancel}>
          Cancel
        </Button>
        {dirty && <span className="text-xs text-muted-foreground">Unsaved changes</span>}
      </div>
    </div>
  )
}
